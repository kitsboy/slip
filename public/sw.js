/*
 * slip service worker — offline shell only.
 *
 * Deliberately dumb: precache the app shell, serve it cache-first, and never touch the
 * network for anything else. A till must not reload itself mid-sale, so updates are NOT
 * applied silently — a new worker waits until the page is closed. (An "update ready"
 * prompt lands with the PWA phase proper.)
 */

const CACHE = 'slip-v1';
const SHELL = ['./', './index.html', './manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).catch(() => undefined));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      return fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => undefined);
          return res;
        })
        .catch(() => caches.match('./index.html').then((shell) => shell ?? Response.error()));
    }),
  );
});
