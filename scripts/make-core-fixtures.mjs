#!/usr/bin/env node
/**
 * Generates tests/vectors/core-derived.json using **Bitcoin Core itself** as the
 * reference oracle (`bitcoin-cli deriveaddresses`).
 *
 * Why: an address encoder that only agrees with itself is not verified. Core is
 * the implementation every wallet interoperates with, so if slip's derived
 * address matches Core's for the same descriptor and index, the base58/bech32/
 * taproot-tweak/sortedmulti wiring is right.
 *
 * This script derives test keys from the public BIP-39 test mnemonic. It is a
 * FIXTURE GENERATOR, not app code — the app itself never sees a seed.
 *
 * Usage: node scripts/make-core-fixtures.mjs
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { mnemonicToSeedSync } from '@scure/bip39';
import { HDKey } from '@scure/bip32';

const MNEMONIC =
  'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';

const seed = mnemonicToSeedSync(MNEMONIC, '');
const root = HDKey.fromMasterSeed(seed);
const fp = root.fingerprint.toString(16).padStart(8, '0');

function account(path) {
  const node = root.derive(path);
  if (!node.publicExtendedKey) throw new Error(`no xpub at ${path}`);
  return node.publicExtendedKey;
}

function core(descriptor, range) {
  const out = execFileSync('bitcoin-cli', ['deriveaddresses', descriptor, range], {
    encoding: 'utf8',
  });
  return JSON.parse(out);
}

const accts = {
  bip84: { path: "m/84'/0'/0'", xpub: account("m/84'/0'/0'") },
  bip86: { path: "m/86'/0'/0'", xpub: account("m/86'/0'/0'") },
  bip44: { path: "m/44'/0'/0'", xpub: account("m/44'/0'/0'") },
  bip49: { path: "m/49'/0'/0'", xpub: account("m/49'/0'/0'") },
  multiA: { path: "m/48'/0'/0'/2'", xpub: account("m/48'/0'/0'/2'") },
  multiB: { path: "m/48'/0'/1'/2'", xpub: account("m/48'/0'/1'/2'") },
  multiC: { path: "m/48'/0'/2'/2'", xpub: account("m/48'/0'/2'/2'") },
};

const CASES = [
  {
    id: 'wpkh',
    scriptType: 'p2wpkh',
    descriptor: `wpkh(${accts.bip84.xpub}/0/*)`,
    account: 'bip84',
  },
  {
    id: 'pkh',
    scriptType: 'p2pkh',
    descriptor: `pkh(${accts.bip44.xpub}/0/*)`,
    account: 'bip44',
  },
  {
    id: 'sh-wpkh',
    scriptType: 'p2sh-p2wpkh',
    descriptor: `sh(wpkh(${accts.bip49.xpub}/0/*))`,
    account: 'bip49',
  },
  {
    id: 'tr',
    scriptType: 'p2tr',
    descriptor: `tr(${accts.bip86.xpub}/0/*)`,
    account: 'bip86',
  },
  {
    id: 'sortedmulti-2of3',
    scriptType: 'sortedmulti-wsh',
    descriptor: `wsh(sortedmulti(2,${accts.multiA.xpub}/0/*,${accts.multiB.xpub}/0/*,${accts.multiC.xpub}/0/*))`,
    account: 'multi',
  },
];

const fixtures = { generatedBy: 'bitcoin-cli deriveaddresses', cases: [] };

for (const c of CASES) {
  let addresses;
  try {
    const info = execFileSync('bitcoin-cli', ['getdescriptorinfo', c.descriptor], {
      encoding: 'utf8',
    });
    const withChecksum = JSON.parse(info).descriptor;
    // Core refuses bare descriptors for tr()/wsh(); always pass the checksummed form.
    addresses = core(withChecksum, '[0,4]');
    fixtures.cases.push({
      id: c.id,
      scriptType: c.scriptType,
      descriptor: withChecksum,
      addresses,
    });
    console.log(`${c.id}: ${addresses.length} addresses`);
  } catch (e) {
    console.error(`FAILED ${c.id}: ${e.message}`);
    process.exitCode = 1;
  }
}

fixtures.accounts = Object.fromEntries(
  Object.entries(accts).map(([k, v]) => [k, { path: v.path, xpub: v.xpub }]),
);
fixtures.fingerprint = fp;

mkdirSync('tests/vectors', { recursive: true });
writeFileSync('tests/vectors/core-derived.json', JSON.stringify(fixtures, null, 2) + '\n');
writeFileSync(
  'tests/vectors/core-derived.README.md',
  [
    '# Where these numbers come from',
    '',
    '`core-derived.json` is generated by `scripts/make-core-fixtures.mjs`, which asks',
    '**Bitcoin Core** (`bitcoin-cli deriveaddresses`, v28) for the first five addresses of',
    'each descriptor. Core is the reference every wallet interoperates with, so a match',
    'proves slip\'s derivation and encoding agree with the ecosystem rather than with itself.',
    '',
    'Test keys come from the public BIP-39 test mnemonic ("abandon … about"). Regenerate with:',
    '',
    '```bash',
    'node scripts/make-core-fixtures.mjs   # requires a synced-enough bitcoind for deriveaddresses',
    '```',
    '',
  ].join('\n'),
);
console.log('wrote tests/vectors/core-derived.json');
